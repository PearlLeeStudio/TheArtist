"""Generate Prefix-Tuning configs + sequential driver.

Three representative genres (classical, country, rock) — same picks as
`setup_peft_compare.py` so the prefix-tuning row in the §3.1 PEFT table
shares the OOD-large-gain / mid-gain / small-gain coverage of the other
methods.

HuggingFace PEFT's PrefixTuningConfig requires the base model to expose
the `past_key_values` HF-transformers interface, which the custom
MusicTransformer does not. The implementation in `prefix_tuning.py`
(PrefixEncoder + PrefixTuningWrapper) is dispatched from `lora_train.py`
under `peft_method: prefix_tuning`.

Output:
  ai/training/configs/lora/peft_compare/<genre>_prefix.yaml
  ai/training/run_prefix_tuning_sweep.sh

Usage:
  cd ai
  python training/setup_prefix_tuning.py
  bash training/run_prefix_tuning_sweep.sh
"""

from __future__ import annotations

from pathlib import Path

PROJECT_DIR = Path(__file__).resolve().parent.parent
LORA_CONFIG_DIR = PROJECT_DIR / "training" / "configs" / "lora"
OUT_DIR = LORA_CONFIG_DIR / "peft_compare"
OUT_DIR.mkdir(parents=True, exist_ok=True)
DRIVER_PATH = PROJECT_DIR / "training" / "run_prefix_tuning_sweep.sh"

GENRES = ["classical", "country", "rock"]

# Small-dataset genres get more epochs for the same wall-time budget,
# mirroring setup_peft_compare.py's policy.
SMALL_EPOCHS = {"classical": 8}
DEFAULT_EPOCHS = 5

# Prefix-tuning hyperparameters (Li & Liang 2021 default = 20 virtual
# tokens; we mirror that). At 20 × 8 layers × 2 (K,V) × 8 heads × 64 dim
# = 163,840 trainable params per adapter (~165k) — sits between BitFit
# (~12k) and IA3 (~13k) at one end and LoRA r=8 (~263k) at the other.
PREFIX_LEN = 20
PREFIX_INIT_STD = 0.02


def _prefix_yaml(genre: str) -> str:
    eps = SMALL_EPOCHS.get(genre, DEFAULT_EPOCHS)
    return f"""# Prefix-tuning PEFT comparison: {genre}
# Custom implementation (see training/prefix_tuning.py) — HF PEFT's
# PrefixTuningConfig requires a HF-transformers past_key_values interface
# that the custom MusicTransformer does not expose, so we ship our own
# PrefixEncoder + PrefixTuningWrapper.

run_name: ft_f1_prefix_{genre}

base_checkpoint: checkpoints/ft_jazz_pop80/best.pt
target_genre: {genre}
sources: ["chordonomicon_{genre}"]

d_model: 512
n_heads: 8
d_ff: 2048
n_layers: 8
max_seq_len: 256
dropout: 0.1

peft_method: prefix_tuning
prefix_len: {PREFIX_LEN}
prefix_init_std: {PREFIX_INIT_STD}

epochs: {eps}
batch_size: 32
gradient_accumulation_steps: 2
lr: 3.0e-4
weight_decay: 0.01
warmup_epochs: 1
max_grad_norm: 1.0
use_amp: true
num_workers: 4
"""


def main() -> None:
    written: list[Path] = []
    for g in GENRES:
        p = OUT_DIR / f"{g}_prefix.yaml"
        p.write_text(_prefix_yaml(g))
        written.append(p)

    # Driver: smallest first (classical ~ 296 -> country ~ 49K -> rock ~ 152K).
    GENRE_ORDER = ["classical", "country", "rock"]
    ordered = [OUT_DIR / f"{g}_prefix.yaml" for g in GENRE_ORDER]

    lines = [
        "#!/usr/bin/env bash",
        "# Auto-generated by training/setup_prefix_tuning.py",
        "# Sequentially trains prefix-tuning runs for the 3 representative",
        "# PEFT-compare genres. Skips a cell whose checkpoint already exists.",
        "set -e",
        "cd \"$(dirname \"$0\")/..\"",
        "echo 'Prefix-tuning sweep starting:' $(date)",
        "",
        "skip_if_done() {",
        "  local rn=\"$1\"",
        "  if [[ -s \"checkpoints/${rn}/prefix_state.pt\" && -s \"checkpoints/${rn}/embedding_extension.pt\" ]]; then return 0; fi",
        "  return 1",
        "}",
        "",
    ]
    total = len(ordered)
    for i, p in enumerate(ordered, start=1):
        rel = p.relative_to(PROJECT_DIR)
        # genre comes from <genre>_prefix.yaml
        genre = p.stem.replace("_prefix", "")
        run_name = f"ft_f1_prefix_{genre}"
        lines.append(f"echo '[{i}/{total}] {rel}'")
        lines.append(f"if skip_if_done '{run_name}'; then")
        lines.append(f"  echo '    SKIP — checkpoint exists at checkpoints/{run_name}'")
        lines.append("else")
        lines.append(
            f"  UV_CACHE_DIR=/tmp/uv-cache uv run python training/lora_train.py --config {rel}"
        )
        lines.append("fi")
        lines.append("")
    lines += [
        "echo 'Prefix-tuning sweep finished:' $(date)",
        "echo 'Now run: UV_CACHE_DIR=/tmp/uv-cache uv run python training/eval_peft_compare.py'",
        "",
    ]
    DRIVER_PATH.write_text("\n".join(lines))
    DRIVER_PATH.chmod(0o755)

    print(f"wrote {len(written)} configs in {OUT_DIR}")
    print(f"wrote driver {DRIVER_PATH}")
    print(f"ordered runs: {len(ordered)} (resumable — checkpoints auto-skip)")
    for p in ordered:
        print(f"  - {p.name}")


if __name__ == "__main__":
    main()
