def main() -> None:
    written: list[Path] = []

    # 1) country full FT (classical and rock already have full_ft configs)
    p = OUT_DIR / "country_full.yaml"
    p.write_text(_country_full_ft_yaml())
    written.append(p)

    # 2) IA3 for all 3 genres
    for g in GENRES:
        p = OUT_DIR / f"{g}_ia3.yaml"
        p.write_text(_ia3_yaml(g))
        written.append(p)

    # 3) BitFit for all 3 genres
    for g in GENRES:
        p = OUT_DIR / f"{g}_bitfit.yaml"
        p.write_text(_bitfit_yaml(g))
        written.append(p)

    # Driver: smallest first (classical 296 -> country 49K -> rock 152K).
    GENRE_ORDER = ["classical", "country", "rock"]
    METHOD_ORDER = ["bitfit", "ia3", "full"]
    ordered: list[Path] = []
    for g in GENRE_ORDER:
        for m in METHOD_ORDER:
            cand = OUT_DIR / f"{g}_{m}.yaml"
            if cand.exists():
                ordered.append(cand)

    lines = [
        "#!/usr/bin/env bash",
        "# Auto-generated by training/setup_peft_compare.py",
        "# Sequentially trains PEFT-comparison runs (BitFit / IA3 / full FT).",
        "# Existing LoRA chosen-rank runs and existing full-FT classical/rock are reused.",
        "set -e",
        "cd \"$(dirname \"$0\")/..\"",
        "echo \"PEFT comparison sweep starting:\" $(date)",
        "",
    ]
    # We also want the existing classical_full_ft + rock_full_ft outcomes; they
    # already live in checkpoints/. Only train new ones.
    for i, p in enumerate(ordered, start=1):
        rel = p.relative_to(PROJECT_DIR)
        lines.append(f"echo '[{i}/{len(ordered)}] {rel}'")
        lines.append(
            f"UV_CACHE_DIR=/tmp/uv-cache uv run python training/lora_train.py --config {rel}"
        )
        lines.append("")
    lines += [
        "echo 'PEFT comparison sweep finished' $(date)",
        "",
    ]
    DRIVER_PATH.write_text("\n".join(lines))
    DRIVER_PATH.chmod(0o755)

    print(f"wrote {len(written)} configs in {OUT_DIR}")
    print(f"wrote driver {DRIVER_PATH}")
    print(f"ordered runs: {len(ordered)}")
    for p in ordered:
        print(f"  - {p.name}")


if __name__ == "__main__":
    main()
