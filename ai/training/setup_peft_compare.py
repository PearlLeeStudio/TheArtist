"""Generate PEFT-comparison configs + sequential driver.

Three representative genres (Bach chorales, country, rock) — picked to
cover the OOD-large-gain end (Bach), the mid-gain end (country), and the
small-gain / arrangement-heavy end (rock).

Four PEFT methods compared per genre:
  - LoRA at the chosen rank        — already trained (re-used)
  - Full fine-tuning               — ai/training/configs/full_ft/*.yaml
                                     (existing for classical, rock; new for country)
  - IA3                            — new
  - BitFit                         — new

Output:
  ai/training/configs/lora/peft_compare/<genre>_<method>.yaml
  ai/training/run_peft_compare_sweep.sh

Usage:
  cd ai
  python training/setup_peft_compare.py
  bash training/run_peft_compare_sweep.sh
"""

from __future__ import annotations

from pathlib import Path

PROJECT_DIR = Path(__file__).resolve().parent.parent
LORA_CONFIG_DIR = PROJECT_DIR / "training" / "configs" / "lora"
FULL_FT_DIR = PROJECT_DIR / "training" / "configs" / "full_ft"
OUT_DIR = LORA_CONFIG_DIR / "peft_compare"
OUT_DIR.mkdir(parents=True, exist_ok=True)
DRIVER_PATH = PROJECT_DIR / "training" / "run_peft_compare_sweep.sh"

GENRES = ["classical", "country", "rock"]


