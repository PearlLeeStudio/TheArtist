"""Generate the FULL 11-genre PEFT comparison configs + resumable driver.

Extends `setup_peft_compare.py` from 3 representative genres to all 11
LoRA target genres for a more robust paper claim. Designed to be run
after the current pipeline completes (and possibly after a laptop
restart). The driver checks for existing checkpoints and skips any
already-trained cell, so it can be killed and restarted safely.

For each genre we generate configs for the three new methods:
  - Full fine-tuning
  - IA3
  - BitFit

LoRA chosen-rank is reused from the existing rank-sweep checkpoints.
The 3-genre subset (classical / country / rock) configs already exist
under `training/configs/lora/peft_compare/`; for those we don't
regenerate — they're picked up if their checkpoints exist, otherwise
the original 3-genre driver should be run first.

Output:
  ai/training/configs/lora/peft_compare_full/<genre>_<method>.yaml  (24 new)
  ai/training/run_peft_compare_full_sweep.sh                        (resumable)
"""

from __future__ import annotations

from pathlib import Path

PROJECT_DIR = Path(__file__).resolve().parent.parent
LORA_CONFIG_DIR = PROJECT_DIR / "training" / "configs" / "lora"
EXISTING_3G_DIR = LORA_CONFIG_DIR / "peft_compare"
OUT_DIR = LORA_CONFIG_DIR / "peft_compare_full"
OUT_DIR.mkdir(parents=True, exist_ok=True)
DRIVER_PATH = PROJECT_DIR / "training" / "run_peft_compare_full_sweep.sh"

GENRES = [
    "blues", "bossa", "classical", "country", "electronic",
    "folk", "funk", "gospel", "hip_hop", "rnb_soul", "rock",
]

# 2026-05-20 Pearl: standardized to 8 epochs across all methods + genres
# for fair PEFT comparison. Previous per-genre 5/8 wall-time-budget split
# was a convenience that broke method-comparison rigor.
UNIFORM_EPOCHS = 8


def _full_yaml(genre: str) -> str:
    eps = UNIFORM_EPOCHS
    return f"""# Full fine-tune on F1 base, target genre: {genre}
# PEFT comparison baseline (11-genre extension).

run_name: ft_f1_full_ft_{genre}

base_checkpoint: checkpoints/ft_jazz_pop80/best.pt
target_genre: {genre}
sources: [\"chordonomicon_{genre}\"]

d_model: 512
n_heads: 8
d_ff: 2048
n_layers: 8
max_seq_len: 256
dropout: 0.1

peft_method: full

epochs: {eps}
batch_size: 32
gradient_accumulation_steps: 2
lr: 1.0e-5
weight_decay: 0.01
warmup_epochs: 1
max_grad_norm: 1.0
use_amp: true
num_workers: 4
"""


def _ia3_yaml(genre: str) -> str:
    eps = UNIFORM_EPOCHS
    return f"""# IA3 PEFT (11-genre extension): {genre}

run_name: ft_f1_ia3_{genre}

base_checkpoint: checkpoints/ft_jazz_pop80/best.pt
target_genre: {genre}
sources: [\"chordonomicon_{genre}\"]

d_model: 512
n_heads: 8
d_ff: 2048
n_layers: 8
max_seq_len: 256
dropout: 0.1

peft_method: ia3
ia3_target_modules: [\"w_k\", \"w_v\"]
ia3_feedforward_modules: []

epochs: {eps}
batch_size: 32
gradient_accumulation_steps: 2
lr: 3.0e-4
weight_decay: 0.01
warmup_epochs: 1
max_grad_norm: 1.0
use_amp: true
num_workers: 4
"""


def _bitfit_yaml(genre: str) -> str:
    eps = UNIFORM_EPOCHS
    return f"""# BitFit PEFT (11-genre extension): {genre}

run_name: ft_f1_bitfit_{genre}

base_checkpoint: checkpoints/ft_jazz_pop80/best.pt
target_genre: {genre}
sources: [\"chordonomicon_{genre}\"]

d_model: 512
n_heads: 8
d_ff: 2048
n_layers: 8
max_seq_len: 256
dropout: 0.1

peft_method: bitfit

epochs: {eps}
batch_size: 32
gradient_accumulation_steps: 2
lr: 3.0e-4
weight_decay: 0.01
warmup_epochs: 1
max_grad_norm: 1.0
use_amp: true
num_workers: 4
"""


def main() -> None:
    written: list[Path] = []
    # Skip the 3 already-set-up genres (classical / country / rock); their
    # configs live in peft_compare/ and will be reused by the resumable driver
    # via checkpoint detection. We still create configs for them under
    # peft_compare_full/ so the driver always has a single source of truth.
    for g in GENRES:
        for method, fn in (("full", _full_yaml), ("ia3", _ia3_yaml), ("bitfit", _bitfit_yaml)):
            p = OUT_DIR / f"{g}_{method}.yaml"
            p.write_text(fn(g))
            written.append(p)

    # Resumable driver: process smallest genres first, skip cells whose
    # checkpoint artifacts already exist on disk.
    GENRE_ORDER = [
        "classical", "funk", "gospel", "rnb_soul", "blues",
        "hip_hop", "bossa", "electronic", "country", "folk", "rock",
    ]
    METHOD_ORDER = ["bitfit", "ia3", "full"]
    ordered: list[Path] = []
    for g in GENRE_ORDER:
        for m in METHOD_ORDER:
            ordered.append(OUT_DIR / f"{g}_{m}.yaml")

    lines = [
        "#!/usr/bin/env bash",
        "# Auto-generated by training/setup_peft_compare_full.py",
        "# RESUMABLE: each cell checks for the existing checkpoint and skips",
        "# if the trained artifact is already there. Safe to kill and restart.",
        "set -e",
        "cd \"$(dirname \"$0\")/..\"",
        "echo 'PEFT-compare FULL (11-genre) sweep starting:' $(date)",
        "",
        "# Helper: skip if the run_name's checkpoint dir already has the",
        "# completed artifact (best.pt for full/bitfit, adapter+embedding for",
        "# lora/ia3). Called as: skip_if_done <run_name> <method>",
        "skip_if_done() {",
        "  local rn=\"$1\"; local m=\"$2\"",
        "  if [[ \"$m\" == \"full\" || \"$m\" == \"bitfit\" ]]; then",
        "    if [[ -s \"checkpoints/${rn}/best.pt\" ]]; then return 0; fi",
        "  else",
        "    if [[ -s \"checkpoints/${rn}/adapter/adapter_config.json\" && -s \"checkpoints/${rn}/embedding_extension.pt\" ]]; then return 0; fi",
        "  fi",
        "  return 1",
        "}",
        "",
    ]
    total = len(ordered)
    for i, p in enumerate(ordered, start=1):
        rel = p.relative_to(PROJECT_DIR)
        # Derive run_name + method from filename: <genre>_<method>.yaml
        stem = p.stem  # e.g. classical_full
        parts = stem.rsplit("_", 1)
        if len(parts) != 2:
            continue
        genre, method = parts
        run_name = f"ft_f1_{'full_ft' if method == 'full' else method}_{genre}"
        lines.append(f"echo '[{i}/{total}] {rel}'")
        lines.append(f"if skip_if_done '{run_name}' '{method}'; then")
        lines.append(f"  echo '    SKIP — checkpoint exists at checkpoints/{run_name}'")
        lines.append("else")
        lines.append(
            f"  UV_CACHE_DIR=/tmp/uv-cache uv run python training/lora_train.py --config {rel}"
        )
        lines.append("fi")
        lines.append("")
    lines += [
        "echo 'PEFT-compare FULL sweep finished:' $(date)",
        "echo 'Now run: UV_CACHE_DIR=/tmp/uv-cache uv run python training/eval_peft_compare.py --all-genres'",
        "",
    ]
    DRIVER_PATH.write_text("\n".join(lines))
    DRIVER_PATH.chmod(0o755)

    print(f"wrote {len(written)} configs in {OUT_DIR}")
    print(f"wrote driver {DRIVER_PATH}")
    print(f"ordered runs: {len(ordered)} (resumable — checkpoints auto-skip)")
    print()
    print("To launch after laptop restart:")
    print("  cd ~/artist/ai")
    print("  nohup bash training/run_peft_compare_full_sweep.sh > /tmp/peft_full.log 2>&1 &")
    print("  disown")
    print()
    print("eval_peft_compare.py currently only iterates 3 genres; will need")
    print("a --all-genres flag added before the post-sweep aggregation.")


if __name__ == "__main__":
    main()
