"""Generate LoRA configs + sequential driver for the multi-seed reliability run.

For each genre and the validation-selected rank, we already have a single-seed
run (seed=42) — its result is in `ai/results/lora_rank_sweep.csv`. This script
sets up two more seeds (123, 7) so the paper can report mean ± std and a
paired comparison vs F1 over 3 seeds per genre.

Output:
  ai/training/configs/lora/multi_seed/<genre>_r<rank>_seed<seed>.yaml
  ai/training/run_multi_seed_sweep.sh

Usage:
  cd ai
  python training/setup_multi_seed.py
  bash training/run_multi_seed_sweep.sh           # sequential, ~10-15h
"""

from __future__ import annotations

import csv
from pathlib import Path

PROJECT_DIR = Path(__file__).resolve().parent.parent
LORA_TEST_CSV = PROJECT_DIR / "results" / "lora_selected_test.csv"
LORA_CONFIG_DIR = PROJECT_DIR / "training" / "configs" / "lora"
OUT_DIR = LORA_CONFIG_DIR / "multi_seed"
OUT_DIR.mkdir(parents=True, exist_ok=True)
DRIVER_PATH = PROJECT_DIR / "training" / "run_multi_seed_sweep.sh"

NEW_SEEDS = [123, 7]


def _base_config_path(genre: str, rank: int) -> Path:
    """The seed=42 config to use as template. Rank 8 lives at <genre>.yaml,
    other ranks live at <genre>_r<rank>.yaml."""
    if rank == 8:
        return LORA_CONFIG_DIR / f"{genre}.yaml"
    return LORA_CONFIG_DIR / f"{genre}_r{rank}.yaml"


def _selected_ranks() -> dict[str, int]:
    out = {}
    with open(LORA_TEST_CSV) as f:
        for r in csv.DictReader(f):
            out[r["genre"]] = int(r["rank"])
    return out


def main() -> None:
    selected = _selected_ranks()
    config_paths: list[Path] = []

    for genre, rank in selected.items():
        base = _base_config_path(genre, rank)
        text = base.read_text()
        for seed in NEW_SEEDS:
            new_run_name = f"ft_f1_lora_{genre}{'' if rank == 8 else f'_r{rank}'}_seed{seed}"
            new_text_lines = []
            saw_run_name = False
            saw_seed = False
            for line in text.splitlines():
                if line.startswith("run_name:"):
                    new_text_lines.append(f"run_name: {new_run_name}")
                    saw_run_name = True
                elif line.startswith("seed:"):
                    new_text_lines.append(f"seed: {seed}")
                    saw_seed = True
                else:
                    new_text_lines.append(line)
            if not saw_run_name:
                raise RuntimeError(f"{base} has no run_name field")
            if not saw_seed:
                # Append seed line. Default 42 is set in lora_train.py if absent;
                # we always want it explicit for the multi-seed configs.
                new_text_lines.append(f"seed: {seed}")
            new_path = OUT_DIR / f"{genre}_r{rank}_seed{seed}.yaml"
            new_path.write_text("\n".join(new_text_lines) + "\n")
            config_paths.append(new_path)
            print(f"wrote {new_path.name} (run_name={new_run_name})")

    # Sequential driver: smallest datasets first so quick wins land early,
    # large datasets (country/folk/rock) at the end. Order by genre size proxy.
    SIZE_ORDER = [
        "classical", "funk", "gospel", "rnb_soul", "blues",
        "hip_hop", "bossa", "electronic", "country", "folk", "rock",
    ]
    ordered: list[Path] = []
    for g in SIZE_ORDER:
        for p in config_paths:
            if p.stem.startswith(f"{g}_"):
                ordered.append(p)
    # Fallback: anything missed (shouldn't happen)
    for p in config_paths:
        if p not in ordered:
            ordered.append(p)

    lines = [
        "#!/usr/bin/env bash",
        "# Auto-generated by training/setup_multi_seed.py",
        "# Runs each multi-seed LoRA config sequentially. Total: 22 runs.",
        "# Logs land at ai/logs/<run_name>_<timestamp>.log .",
        "set -e",
        "cd \"$(dirname \"$0\")/..\"",
        "echo \"Multi-seed sweep starting: 22 runs\"",
        "date",
        "",
    ]
    for i, p in enumerate(ordered, start=1):
        rel = p.relative_to(PROJECT_DIR)
        lines.append(f"echo '[{i}/{len(ordered)}] {rel}'")
        lines.append(
            f"UV_CACHE_DIR=/tmp/uv-cache uv run python training/lora_train.py --config {rel}"
        )
        lines.append("")
    lines += [
        "echo 'Multi-seed sweep finished'",
        "date",
        "",
    ]
    DRIVER_PATH.write_text("\n".join(lines))
    DRIVER_PATH.chmod(0o755)
    print(f"\nwrote {DRIVER_PATH}")
    print(f"{len(config_paths)} configs, {len(ordered)} ordered runs")


if __name__ == "__main__":
    main()
