"""§3.3: Multi-seed × all 5 ranks for small-spread genres.

Generates configs + a resumable driver for the 4 small-spread genres (funk,
hip_hop, rnb_soul, rock) — these are the genres where rank-vs-rank delta at
seed=42 was <1pp, so the original chosen-rank multi-seed sweep isn't enough
to claim "rank X is best" with statistical confidence.

We already have:
  - seed=42 for all (genre, rank) cells from the original LoRA rank sweep
  - chosen-rank × seeds {123, 7} from the current multi-seed sweep

So this script only emits the missing cells: 4 small-spread genres × 4
non-chosen ranks × 2 new seeds = 32 new runs (~80-100h sequential).

Driver is resumable: each cell checks for the existing adapter+embedding
and skips if present.

Output:
  ai/training/configs/lora/multi_seed_full_rank/<genre>_r<rank>_seed<seed>.yaml
  ai/training/run_multi_seed_full_rank_sweep.sh

Usage:
  cd ai
  python training/setup_multi_seed_full_rank.py
  bash training/run_multi_seed_full_rank_sweep.sh
"""

from __future__ import annotations

import csv
from pathlib import Path

PROJECT_DIR = Path(__file__).resolve().parent.parent
LORA_TEST_CSV = PROJECT_DIR / "results" / "lora_selected_test.csv"
LORA_CONFIG_DIR = PROJECT_DIR / "training" / "configs" / "lora"
OUT_DIR = LORA_CONFIG_DIR / "multi_seed_full_rank"
OUT_DIR.mkdir(parents=True, exist_ok=True)
DRIVER_PATH = PROJECT_DIR / "training" / "run_multi_seed_full_rank_sweep.sh"

NEW_SEEDS = [123, 7]
ALL_RANKS = [4, 8, 16, 32, 64]

# Small-spread = rank-to-rank f1 delta at seed=42 < 1pp.
# tbd §3.3: funk 0.12pp, hip_hop 0.05pp, rnb_soul 0.07pp, rock 0.86pp.
SMALL_SPREAD_GENRES = ["funk", "hip_hop", "rnb_soul", "rock"]


def _base_config_path(genre: str, rank: int) -> Path:
    if rank == 8:
        return LORA_CONFIG_DIR / f"{genre}.yaml"
    return LORA_CONFIG_DIR / f"{genre}_r{rank}.yaml"


def _selected_ranks() -> dict[str, int]:
    out = {}
    with open(LORA_TEST_CSV) as f:
        for r in csv.DictReader(f):
            out[r["genre"]] = int(r["rank"])
    return out


def main() -> None:
    selected = _selected_ranks()
    config_records: list[tuple[str, int, int, Path]] = []  # (genre, rank, seed, path)

    for genre in SMALL_SPREAD_GENRES:
        chosen_rank = selected[genre]
        non_chosen = [r for r in ALL_RANKS if r != chosen_rank]
        for rank in non_chosen:
            base = _base_config_path(genre, rank)
            if not base.exists():
                raise FileNotFoundError(f"missing base config for {genre} r={rank}: {base}")
            text = base.read_text()
            for seed in NEW_SEEDS:
                new_run_name = f"ft_f1_lora_{genre}{'' if rank == 8 else f'_r{rank}'}_seed{seed}"
                new_text_lines = []
                saw_run_name = False
                saw_seed = False
                for line in text.splitlines():
                    if line.startswith("run_name:"):
                        new_text_lines.append(f"run_name: {new_run_name}")
                        saw_run_name = True
                    elif line.startswith("seed:"):
                        new_text_lines.append(f"seed: {seed}")
                        saw_seed = True
                    else:
                        new_text_lines.append(line)
                if not saw_run_name:
                    raise RuntimeError(f"{base} has no run_name field")
                if not saw_seed:
                    new_text_lines.append(f"seed: {seed}")
                new_path = OUT_DIR / f"{genre}_r{rank}_seed{seed}.yaml"
                new_path.write_text("\n".join(new_text_lines) + "\n")
                config_records.append((genre, rank, seed, new_path))
                print(f"wrote {new_path.name} (run_name={new_run_name})")

    # Order: cheap genres first so we get partial wins.
    # Funk has 285 test seqs (smallest), rock has 4891 (largest).
    SIZE_ORDER = ["funk", "hip_hop", "rnb_soul", "rock"]
    config_records.sort(key=lambda r: (SIZE_ORDER.index(r[0]), r[1], r[2]))

    lines = [
        "#!/usr/bin/env bash",
        "# Auto-generated by training/setup_multi_seed_full_rank.py",
        "# RESUMABLE: skips cells whose adapter+embedding already exist.",
        "# Total: 32 runs (4 small-spread genres × 4 non-chosen ranks × 2 new seeds).",
        "# Logs land at ai/logs/<run_name>_<timestamp>.log .",
        "set -e",
        "cd \"$(dirname \"$0\")/..\"",
        "echo \"Multi-seed full-rank sweep starting: 32 runs\"",
        "date",
        "",
        "skip_if_done() {",
        "  local rn=\"$1\"",
        "  if [[ -s \"checkpoints/${rn}/adapter/adapter_config.json\" && -s \"checkpoints/${rn}/embedding_extension.pt\" ]]; then return 0; fi",
        "  return 1",
        "}",
        "",
    ]
    for i, (genre, rank, seed, path) in enumerate(config_records, start=1):
        rn = f"ft_f1_lora_{genre}{'' if rank == 8 else f'_r{rank}'}_seed{seed}"
        rel = path.relative_to(PROJECT_DIR)
        lines += [
            f"echo '[{i}/{len(config_records)}] {rel}'",
            f"if skip_if_done '{rn}'; then",
            f"  echo '    SKIP — checkpoint exists at checkpoints/{rn}'",
            "else",
            f"  UV_CACHE_DIR=/tmp/uv-cache uv run python training/lora_train.py --config {rel}",
            "fi",
            "",
        ]
    lines += [
        "echo 'Multi-seed full-rank sweep finished'",
        "date",
        "",
    ]
    DRIVER_PATH.write_text("\n".join(lines))
    DRIVER_PATH.chmod(0o755)
    print(f"\nwrote {DRIVER_PATH}")
    print(f"{len(config_records)} configs / runs")


if __name__ == "__main__":
    main()
